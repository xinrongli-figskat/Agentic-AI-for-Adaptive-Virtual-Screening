"""Finalize definition-independent measurements and a closed manifest."""
import csv
import hashlib
import json
from datetime import datetime,timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parent
now=datetime.now(timezone.utc).isoformat()
rows=list(csv.DictReader((ROOT/'credential_62_measurement_partial_v2.csv').open()))
for row in rows:
    row['source_tier']='not_assigned_pending_scope_definition'
path=ROOT/'credential_62_measurement_final_partial.csv'
assert not path.exists()
with path.open('w',newline='',encoding='utf-8') as f:
    writer=csv.DictWriter(f,fieldnames=list(rows[0]));writer.writeheader();writer.writerows(rows)
summary=json.loads((ROOT/'credential_summary_partial_v2.json').read_text())
summary.update({'finalized_utc':now,'measurement_table':path.name,
    'source_tier_assignment_performed':False,'unresolved_source_tier_rows':62,
    'source_scope_note':'Global compound_records provenance and assay-supporting activity provenance are reported separately. Equality of these readings is not a requirement or a gate. No source tier is assigned pending definition clarification.',
    'previous_diagnostic_snapshots_preserved':True})
(ROOT/'credential_summary_final_partial.json').write_text(json.dumps(summary,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
assert len(rows)==62
assert sum(int(r['multi_molregno_count']) for r in rows)==5
assert sum(int(r['unclassified_identity_count']) for r in rows)==2526
assert sum(abs(sum(float(r[k]) for k in ['full_match_frac','skeleton_only_frac','single_source_frac'])-1)<1e-9 for r in rows)==8
audit={'checked_utc':now,'rows':62,'multi_total':5,'unclassified_total':2526,'three_fraction_sum_pass_rows':8,
    'all_deminimis_pass':all(float(r['multi_molregno_fraction'])<=.01 for r in rows),
    'glm_calls':0,'gate_decisions_written':False,'measurement_status':'partial_tier_b',
    'scope_equality_not_required':True}
(ROOT/'measurement_validation.json').write_text(json.dumps(audit,indent=2)+'\n',encoding='utf-8')
log='''# D7-D execution log

Post-exposure. All writes in this task are under outputs/d7_20261021/d_identity_gate_v2/. GLM calls: 0.

- The root reported all eleven D7 prerequisite hashes verified in preflight_20261021T094803Z.json. This task independently rechecked the R3 CSV hash and rule-lock hashes. The database was opened with SQLite mode=ro.
- 2026-10-21T09:49:56.613816+00:00: rule-lock timestamp, generated by lock_rule.py; exact D6 A-2 byte extract preserved.
- 2026-10-21T09:52:59.995346+00:00 to 09:53:01.057697+00:00: read-only source measurements from the 62 saved R3 support sets. All support counts and hit-support counts match R3. Original partial snapshot retained.
- 2026-10-21T09:55:21.605477+00:00: recorded resolution of three conservative multi-key placeholders. Every constituent alternate-source set is empty, so all representative/union choices agree on single_source. This implements the D7 de minimis instruction without choosing a new aggregation rule. Original snapshot retained.
- Source-tier readings were initially shown with a provisional common-value field. Root review correctly noted that equality of global provenance and assay provenance is not required by D6. The final partial table assigns no source tier and reports both readings separately. No gate decision had used the provisional field. Earlier snapshots remain intact.
- Final partial table: 62 rows, 25,813 identities, five multi-molregno occurrences all <=1%, 2,526 identities not assigned by the literal three-class partition, 43 assays with activity provenance src_id 37 absent from the tier map. Only eight rows have three defined fractions summing to one. This is explicitly not a completed credential table.
- D3 candidate-criteria registration completed. Gate application, TACE/TNAP validation and GLM reevaluation were not performed because measurement definitions require a Tier B clarification.
- Private per-identity artifacts are Git-ignored; the rule text and all D6 historical outputs remain unchanged.

This log is a retrospective execution record written at CLOSEOUT_TIME; the event timestamps above are copied from their generated receipts and are not claimed as this file's creation time.
'''.replace('CLOSEOUT_TIME',now)
(ROOT/'RUN_LOG.md').write_text(log,encoding='utf-8')
members=[]
for file in sorted(ROOT.rglob('*')):
    if file.is_file() and file.name!='MANIFEST.json':
        members.append({'path':file.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(file.read_bytes()).hexdigest(),'bytes':file.stat().st_size})
(ROOT/'MANIFEST.json').write_text(json.dumps({'created_utc':now,'post_exposure':True,'status':'blocked_tier_b','glm_calls':0,'files':members},indent=2)+'\n',encoding='utf-8')
print(json.dumps({'manifest_members':len(members),'manifest_sha256':hashlib.sha256((ROOT/'MANIFEST.json').read_bytes()).hexdigest(),'validation':audit},indent=2))
